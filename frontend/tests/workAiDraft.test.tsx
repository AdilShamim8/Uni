/* Controllable fake live adapter                                       */
/* ------------------------------------------------------------------ */

interface FakeScript {
  /** Emit these chunks in order; a null entry parks the stream forever. */
  chunks: (string | null)[]
  failWith?: string
}

function fakeAdapter(script: FakeScript): ChatAdapter {
  return {
    id: 'fake-live',
    label: 'Fake live',
    async stream(_request, handlers: ChatStreamHandlers, signal: AbortSignal) {
      handlers.onStart({})
      for (const chunk of script.chunks) {
        if (signal.aborted) {
          handlers.onDone('stopped')
          return
        }
        if (chunk === null) {
          // Park until aborted — lets the test press Stop mid-stream.
          await new Promise<void>((resolve) => {
            signal.addEventListener('abort', () => resolve(), { once: true })
          })
          handlers.onDone('stopped')
          return
        }
        handlers.onDelta(chunk)
        await new Promise((resolve) => setTimeout(resolve, 1))
      }
      if (script.failWith) {
        handlers.onError({ code: 'provider_error', message: script.failWith })
        return
      }
      handlers.onDone('complete')
    },
  }
}

const MODEL = {
  providerId: '',
  modelId: 'demo-standard',
  providerLabel: 'Test provider',
  modelLabel: 'Demo Standard',
}

function connectFirstProvider(): void {
  const provider = useAppStore.getState().providers[0]
  MODEL.providerId = provider.id
  useAppStore.getState().setCredential(provider.id, {
    providerId: provider.id,
    apiKey: 'test-key-DO-NOT-PERSIST',
    status: 'connected',
    lastCheckedAt: Date.now(),
    lastError: null,
    discoveredModels: [],
  })
}

function createDraftTask(): string {
  return useWorkStore.getState().createTask({
    title: 'Draft the launch note',
    goal: 'A short launch note',
    deliverable: 'email-draft',
    mode: 'ai-draft',
    draftConfig: {
      model: { ...MODEL },
      instructions: 'Warm tone',
      contextText: 'The product ships Friday.',
    },
  })
}

/* ------------------------------------------------------------------ */
/* Store-level behavior                                                 */
/* ------------------------------------------------------------------ */

describe('work AI-draft runner (store)', () => {
  setupAppTest()

  it('streams content into the report and marks it provider-generated', async () => {
    connectFirstProvider()
    setAiAdapterFactoryForTests(() =>
      fakeAdapter({ chunks: ['# Launch note\n', '\n', 'We ship Friday.'] }),
    )
    const id = createDraftTask()

    useWorkStore.getState().runTask(id)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[id].status).toBe('ready_for_review')
    })

    const task = useWorkStore.getState().tasks[id]
    expect(task.report?.markdown).toBe('# Launch note\n\nWe ship Friday.')
    expect(task.report?.provenance).toBe('provider-generated')
    expect(task.report?.generatedBy?.modelLabel).toBe('Demo Standard')
    expect(task.report?.contextIncluded).toBe(true)
    expect(task.report?.stoppedPartial).toBe(false)
    expect(task.error).toBeNull()
    // Run-scoped events: start + streaming + readiness.
    const labels = task.events.map((event) => event.label).join(' | ')
    expect(labels).toContain('Draft generation started')
    expect(labels).toContain('Streaming draft content from Demo Standard')
    expect(labels).toContain('Draft ready for review — provider-generated by Demo Standard')
  })

  it('stop preserves partial content, flags it, and requires an explicit new run', async () => {
    connectFirstProvider()
    setAiAdapterFactoryForTests(() => fakeAdapter({ chunks: ['# Partial draft\n', null] }))
    const id = createDraftTask()

    useWorkStore.getState().runTask(id)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[id].report?.markdown).toBe('# Partial draft\n')
    })

    useWorkStore.getState().pauseTask(id)
    const task = useWorkStore.getState().tasks[id]
    expect(task.status).toBe('paused')
    expect(task.report?.markdown).toBe('# Partial draft\n')
    expect(task.report?.stoppedPartial).toBe(true)
    expect(task.events.at(-1)?.label).toContain('partial draft preserved')
  })

  it('failure records the error and keeps partial content for review', async () => {
    connectFirstProvider()
    setAiAdapterFactoryForTests(() =>
      fakeAdapter({ chunks: ['# Half a draft\n'], failWith: 'HTTP 429 — rate limited' }),
    )
    const id = createDraftTask()

    useWorkStore.getState().runTask(id)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[id].status).toBe('failed')
    })

    const task = useWorkStore.getState().tasks[id]
    expect(task.error).toBe('HTTP 429 — rate limited')
    expect(task.report?.markdown).toBe('# Half a draft\n')
    expect(task.report?.stoppedPartial).toBe(true)
    expect(task.events.some((event) => event.label.includes('Draft request failed'))).toBe(true)
  })

  it('isolates concurrent runs per task — stopping one leaves the other streaming', async () => {
    connectFirstProvider()
    const parking = fakeAdapter({ chunks: ['# A\n', null] })
    setAiAdapterFactoryForTests(() => parking)
    const first = createDraftTask()
    const second = createDraftTask()

    useWorkStore.getState().runTask(first)
    useWorkStore.getState().runTask(second)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[first].report?.markdown).toBe('# A\n')
      expect(useWorkStore.getState().tasks[second].report?.markdown).toBe('# A\n')
    })

    useWorkStore.getState().pauseTask(first)
    expect(useWorkStore.getState().tasks[first].status).toBe('paused')
    expect(useWorkStore.getState().tasks[second].status).toBe('running')

    useWorkStore.getState().cancelTask(second)
    expect(useWorkStore.getState().tasks[second].status).toBe('cancelled')
  })

  it('fails honestly when the provider is not connected', async () => {
    // No credential connected.
    setAiAdapterFactoryForTests(() => fakeAdapter({ chunks: ['never'] }))
    const id = createDraftTask()

    useWorkStore.getState().runTask(id)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[id].status).toBe('failed')
    })
    expect(useWorkStore.getState().tasks[id].error).toContain('not connected')
  })

  it('never persists credentials into the work slice', async () => {
    useWorkStore.getState().initialize()
    connectFirstProvider()
    setAiAdapterFactoryForTests(() =>
      fakeAdapter({ chunks: ['# Safe\n'] }),
    )
    const id = createDraftTask()
    useWorkStore.getState().runTask(id)
    await waitFor(() => {
      expect(useWorkStore.getState().tasks[id].status).toBe('ready_for_review')
    })

    flushWorkPersistence()
    const raw = localStorage.getItem('universe:work:v1') ?? ''
    expect(raw).not.toContain('test-key-DO-NOT-PERSIST')
    expect(raw).not.toContain('apiKey')
    // The saved task keeps its model snapshot and provenance.
    expect(loadWorkSlice().state?.tasks[0].report?.provenance).toBe('provider-generated')
  })

  it('loads pre-AI-draft tasks as demo mode with normalized reports', () => {
    // A v1 work slice written before this feature (no mode, no draftConfig,
    // minimal report) must still load.
    localStorage.setItem(
      'universe:work:v1',
      JSON.stringify({
        version: 1,
        savedAt: Date.now(),
        payload: {
          tasks: [
            {
              id: 'task-legacy',
              title: 'Legacy demo task',
              goal: 'Old goal',
              deliverable: 'research-report',
              agentId: null,
              projectId: null,
              attachments: [],
              status: 'completed',
              createdAt: 1,
              updatedAt: 2,
              events: [],
              currentRunId: null,
              planCursor: 0,
              runAnswers: [],
              interrupted: false,
              inputRequest: null,
              report: {
                template: 'research',
                markdown: '# Old',
                artifactId: null,
              },
            },
          ],
        },
      }),
    )

    resetWorkStoreForTests({ keepStorage: true })
    useWorkStore.getState().initialize()

    const task = useWorkStore.getState().tasks['task-legacy']
    expect(task).toBeDefined()
    expect(task.mode).toBe('demo')
    expect(task.draftConfig).toBeNull()
    expect(task.report?.provenance).toBe('demo-simulation')
    expect(task.report?.stoppedPartial).toBe(false)
    expect(task.report?.markdown).toBe('# Old')
  })
})

